-- 01_tables.sql
-- Inventory and Sales: table definitions
-- Run this script first (other objects depend on these tables).

CREATE TABLE product_categories (
  category_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  category_name VARCHAR2(50) NOT NULL
);

CREATE TABLE products (
  product_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  category_id   NUMBER REFERENCES product_categories (category_id),
  product_name  VARCHAR2(100) NOT NULL,
  price         NUMBER(10,2) NOT NULL CHECK (price > 0),
  stock_qty     NUMBER DEFAULT 0 NOT NULL CHECK (stock_qty >= 0),
  reorder_level NUMBER DEFAULT 5
);

CREATE TABLE customers (
  customer_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  customer_name VARCHAR2(100) NOT NULL,
  phone         VARCHAR2(30),
  city          VARCHAR2(50)
);

CREATE TABLE orders (
  order_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  customer_id NUMBER REFERENCES customers (customer_id),
  order_date  DATE DEFAULT SYSDATE,
  status      VARCHAR2(20) DEFAULT 'Draft'
);

CREATE TABLE order_items (
  item_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  order_id   NUMBER NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,
  product_id NUMBER NOT NULL REFERENCES products (product_id),
  quantity   NUMBER NOT NULL CHECK (quantity > 0),
  unit_price NUMBER(10,2)
);
